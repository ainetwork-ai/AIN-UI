// src/catalog/standard.json → src/catalog/standard.gen.ts, so the catalog ships inside the JS bundle
// (a JSON import needs an import attribute that not every bundler accepts).
import { readFileSync, writeFileSync } from "node:fs";
const doc = JSON.parse(readFileSync(new URL("../src/catalog/standard.json", import.meta.url), "utf8"));
// AINUI v1 names that the standard components keep understanding.
const dyn = (schema, description) => ({ description, anyOf: [schema, { $ref: "common_types.json#/$defs/DataBinding" }, { $ref: "common_types.json#/$defs/FunctionCall" }] });
Object.assign(doc.components.Button.properties, {
  action: { $ref: "common_types.json#/$defs/Action", description: "Same as onClick (the A2UI basic catalog's name for it)." },
  confirm: dyn({ type: "string" }, "Ask this question first; the action is sent only if the user agrees. Use it for anything destructive."),
  tone: dyn({ type: "string", enum: ["default", "danger"] }, "\"danger\" for a destructive action."),
});
doc.components.Grid.properties.minItemWidth = dyn({ type: ["number", "string"] }, "Same as minChildWidth.");
// Components the playground catalog has beyond the standard ones, which make dashboards and summaries read well.
const rich = JSON.parse(readFileSync(new URL("../src/catalog/rich.json", import.meta.url), "utf8"));
Object.assign(doc.components, rich.components);
// The AIN components and the catalog's own identity.
const ain = JSON.parse(readFileSync(new URL("../src/catalog/ain.json", import.meta.url), "utf8"));
Object.assign(doc.components, ain.components);
doc.catalogId = "https://ainui.ainetwork.xyz/catalogs/ainui/v2/catalog.json";
doc.title = "AIN-UI catalog";
doc.description = "A2UI 1.0 catalog of AIN-UI: the 69 standard generative-UI components (same names and props as CopilotKit's Gen UI 2.0 standard catalog) and the AIN components for files, upload, x402 payment, folder chat and pickers.";
doc.instructions = ain.instructions;
doc.$defs.anyComponent = { oneOf: Object.keys(doc.components).map((name) => ({ $ref: `#/components/${name}` })) };
writeFileSync(new URL("../src/catalog/standard.gen.ts", import.meta.url),
  `// Generated by scripts/standard.mjs from standard.json and ain.json. Do not edit.\n` +
  `/** The AINUI catalog document (A2UI 1.0): ${Object.keys(doc.components).length} components, ${Object.keys(doc.functions).length} functions. */\n` +
  `export const AINUI_CATALOG_DOCUMENT: Record<string, any> = JSON.parse(${JSON.stringify(JSON.stringify(doc))});\n` +
  `/** Names of the standard components (the rest are AIN's own). */\n` +
  `export const RICH_COMPONENT_NAMES: readonly string[] = ${JSON.stringify(Object.keys(rich.components))};\n` +
  `export const STANDARD_COMPONENT_NAMES: readonly string[] = ${JSON.stringify(Object.keys(doc.components).filter((n) => !(n in ain.components) && !(n in rich.components)))};\n`);
